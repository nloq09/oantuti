import {mountTournamentTabs} from './tournament-tabs.js';
import {mountTournamentCreate} from './tournament-create-form.js';
import {mountHub} from './tournament-hub.js';
import {tournamentRoute} from './tournament-routes.js';
import {createTournament,addParticipant} from './tournament-api.js';
import {sessionRequest} from '../api/auth-api.js';
import {refreshBots,savedBots} from '../api/bot-api.js';
import {getAccount} from '../account/account-session.js';
import {toast} from '../ui/toast.js';
const find=id=>document.getElementById(id);let hub;
const tabs=mountTournamentTabs({discover:find('tab-discover'),create:find('tab-create')},{discover:find('panel-discover'),create:find('panel-create')},{onChange:()=>hub?.request(true,'tab',{replace:true})});
hub=mountHub(find('tournament-list'),{onCreate:()=>tabs.select('create',{focus:true}),active:()=>tabs.active==='discover'});
const account=await getAccount().catch(error=>{toast(error.message,true);return null;});
if(account)await refreshBots().catch(error=>toast(error.message,true));
mountTournamentCreate(find('panel-create'),{account,bots:savedBots(),create:createTournament,request:sessionRequest,add:addParticipant});
find('join-tournament').onsubmit=event=>{event.preventDefault();const value=find('tournament-code').value.trim();let target=value;try{target=new URL(value).searchParams.get('id')||'';}catch{}if(!/^[\da-f]{8}-[\da-f]{4}-[\da-f]{4}-[\da-f]{4}-[\da-f]{12}$/i.test(target)){toast('Nhập mã giải đấu hoặc link mời hợp lệ.',true);return;}location.href=tournamentRoute(target);};
addEventListener('pagehide',event=>{if(!event.persisted)tabs.stop();});
